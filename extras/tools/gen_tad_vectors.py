"""Write extras/tests/vectors/tad_connect_d100_d102.h from a RetroIO capture decode.

Input: RetroIO's src/pcap-decode-sample.json (a list of decoded XMSG frames). Records 244-341 are
one complete CONNECT-TO session: D100 (node 100) asks D102 (node 102) for a terminal, logs in,
lists files and logs out. The file lists each machine's frames as a group, so the order between
the two groups is rebuilt from the ACK numbers: TRIGGERS maps each host Flags1 to the asker Flags1
after which the host sent it (found by reading where the asker's ACK of each host frame sits
among the asker's own frames).

    python3 extras/tools/gen_tad_vectors.py <pcap-decode-sample.json> <output .h>
"""
import json
import sys

FIRST, LAST = 244, 342  # the records of the session, end exclusive
SPLIT = 293             # asker group 244-292, host group 293-341

TRIGGERS = {
    0x12F: 0xF8, 0x130: 0xF9, 0x131: 0xF9, 0x132: 0xFB, 0x133: 0xFB, 0x134: 0xFC,
    0x135: 0xFD, 0x136: 0xFE, 0x137: 0xFF, 0x138: 0x100, 0x139: 0x101, 0x13A: 0x102,
    0x13B: 0x102, 0x13C: 0x104, 0x13D: 0x104, 0x13E: 0x106, 0x13F: 0x106, 0x140: 0x108,
    0x141: 0x109, 0x142: 0x10A, 0x143: 0x10B, 0x144: 0x10C, 0x145: 0x10D, 0x146: 0x10D,
    0x147: 0x10F,
}

HEAD = """/*
 * tad_connect_d100_d102.h - one complete CONNECT-TO session between two real SINTRAN machines.
 *
 * SPDX-License-Identifier: MIT
 * Copyright (c) 2026 Ronny Hansen
 *
 * GENERATED by extras/tools/gen_tad_vectors.py from RetroIO src/pcap-decode-sample.json,
 * records 244-341: D100 (node 100) asks D102 (node 102) for a terminal, logs in, lists files and
 * logs out. The file lists each machine's frames as a group, so the order between the two groups
 * is rebuilt from the ACK numbers: `after` is the asker Flags1 after which the host frame was
 * sent. Raw frames are the LAPB information field (SINTRAN header onward). Do not edit;
 * regenerate.
 */
#ifndef TAD_CONNECT_D100_D102_H
#define TAD_CONNECT_D100_D102_H

#include <stdint.h>

typedef struct TadVecFrame
{
    uint16_t flags1;
    uint16_t after; /* host frames: the asker Flags1 that triggers it; asker frames: 0 */
    const char *hex;
} TadVecFrame;
"""


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 1
    with open(sys.argv[1], encoding="utf-8") as f:
        records = json.load(f)
    asker = [x for x in records[FIRST:SPLIT] if x["Header"]["Subtype"] == "Data"]
    host = [x for x in records[SPLIT:LAST] if x["Header"]["Subtype"] == "Data"]
    lines = [HEAD.rstrip("\n"), "", "// clang-format off",
             "/* The asker (D100) frames, in the order sent. */",
             "static const TadVecFrame k_tad_asker_frames[] = {"]
    for x in asker:
        lines.append('    {0x%04X, 0, "%s"},' % (x["Header"]["Flags1"], x["RawHex"]))
    lines += ["};", "", "/* The host (D102) frames, in the order sent. */",
              "static const TadVecFrame k_tad_host_frames[] = {"]
    for x in host:
        f1 = x["Header"]["Flags1"]
        lines.append('    {0x%04X, 0x%04X, "%s"},' % (f1, TRIGGERS[f1], x["RawHex"]))
    lines += ["};", "", "// clang-format on", "", "#endif /* TAD_CONNECT_D100_D102_H */"]
    with open(sys.argv[2], "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d asker frames, %d host frames" % (len(asker), len(host)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
